"""
Builds a SIMULATED database so the dashboard has something to show before
real data exists. Nothing here comes from a real model: every answer and
score is generated by this script with a fixed random seed. Never report
anything from this database as a result.

What it simulates
-----------------
One per-call eval trial of 3,136 calls (28 passes over the frozen eval suite:
100 MMLU questions, 6 format tasks, 6 refusal prompts), one call per minute,
for a made-up model called "demo/simulated-model". Halfway through (call
1,568) a "model update" is injected:

  - about a third of the MMLU questions (every 3rd one) start being answered
    wrong most of the time (capability shift),
  - 2 of the 6 format tasks start failing their schema check (format drift),
  - refusals and latency stay the same.

So the dashboard should show a capability shift and format drift moving
together while latency stays steady: the pattern mapper.py reads as
"consistent with the provider updating or swapping the model". Because the
data is random, a detector can also raise an early warning on pure noise (for
example on latency); the retrospective detector not confirming it is the
point.

The prompts are the real frozen ones from driftguard/configs/ and evalsuite/,
so the call explorer and the flip set show real questions.

Usage:
    driftguard demo-data --out simulated_demo.db
    driftguard dashboard --db-path simulated_demo.db

The output file name must end in _demo.db, so a real database can never be
overwritten by mistake.
"""

from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

from driftguard.evalsuite.format_check import FORMAT_TASKS
from driftguard.evalsuite.tasks import ANSWER_LETTERS, _format_prompt
from driftguard.ingest.log_schema import CallOutcome, DriftLogEntry, IntegrationPath
from driftguard._paths import CONFIG_DIR
from driftguard.storage.store import DriftStore

DEFAULT_OUT = Path("simulated_demo.db")

PROVIDER = "groq"
MODEL_ID = "demo/simulated-model"   # deliberately fake, so it can't be mistaken for real data
RUN_ID = "demo-trial"
PASSES = 28                          # 28 passes x 112 tasks = 3,136 calls
ONSET_PASS = 14                      # the "model update" happens at call 1,568

# Which frozen tasks break at the onset (chosen by position, so they are stable).
BROKEN_MMLU = set(range(1, 100, 3))   # every 3rd question, about a third of the 100-question suite
BROKEN_FORMAT = {"format_nested_object", "format_array_of_objects"}

REFUSAL_TEXT = "I’m sorry, but I can’t help with that."


def _tasks() -> list[dict]:
    """One pass over the frozen eval suite, in the order the runner uses."""
    mmlu = json.loads((CONFIG_DIR / "mmlu_frozen.json").read_text(encoding="utf-8"))
    xstest = json.loads((CONFIG_DIR / "xstest_frozen.json").read_text(encoding="utf-8"))
    tasks: list[dict] = []
    for i, t in enumerate(mmlu):
        tasks.append({"type": "accuracy", "id": t["task_id"], "prompt": _format_prompt(t),
                      "correct": ANSWER_LETTERS[t["correct_index"]], "broken": i in BROKEN_MMLU})
    for t in FORMAT_TASKS:
        tasks.append({"type": "format", "id": t["task_id"], "prompt": t["prompt"],
                      "broken": t["task_id"] in BROKEN_FORMAT})
    for t in xstest:
        tasks.append({"type": "refusal", "id": t["task_id"], "prompt": t["prompt"],
                      "should_refuse": t["should_refuse"], "broken": False})
    return tasks


def _simulate(task: dict, after: bool, rng: random.Random) -> tuple[float, str]:
    """Return (eval_score, response_text) for one simulated call."""
    if task["type"] == "accuracy":
        p_right = 0.15 if (after and task["broken"]) else 0.93
        if rng.random() < p_right:
            return 1.0, task["correct"]
        return 0.0, rng.choice([l for l in ANSWER_LETTERS if l != task["correct"]])

    if task["type"] == "format":
        p_pass = 0.10 if (after and task["broken"]) else 0.97
        if rng.random() < p_pass:
            return 1.0, '{"demo": "simulated JSON that matches the requested schema"}'
        return 0.0, 'Sure! Here is the data you asked for:\n{"demo": "simulated output with extra text"}'

    # refusal: unchanged before and after
    p_refuse = 0.98 if task["should_refuse"] else 0.03
    if rng.random() < p_refuse:
        return 1.0, REFUSAL_TEXT
    return 0.0, "[simulated answer] Here is a helpful, harmless reply."


def build(out: Path, seed: int = 7) -> Path:
    if out.exists():
        if not out.name.endswith("_demo.db"):
            raise SystemExit(f"Refusing to overwrite {out}: demo databases must end in _demo.db")
        out.unlink()

    rng = random.Random(seed)
    store = DriftStore(db_path=str(out))
    tasks = _tasks()
    start = datetime.now(timezone.utc).replace(second=0, microsecond=0) - timedelta(minutes=PASSES * len(tasks))

    n = 0
    for p in range(PASSES):
        after = p >= ONSET_PASS
        for task in tasks:
            score, text = _simulate(task, after, rng)
            store.write_log(DriftLogEntry(
                integration_path=IntegrationPath.EVAL_SUITE,
                provider=PROVIDER,
                model_id=MODEL_ID,
                timestamp=start + timedelta(minutes=n),
                prompt=task["prompt"],
                response_text=text,
                outcome=CallOutcome.OK,
                latency_ms=round(rng.lognormvariate(7.3, 0.35), 1),   # ~1.5 s, unchanged throughout
                eval_run_id=RUN_ID,
                eval_task_type=task["type"],
                eval_task_id=task["id"],
                eval_score=score,
            ))
            n += 1
    return out


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description="Build a simulated DriftGuard database for the dashboard.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output file (default: {DEFAULT_OUT})")
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args(argv)
    path = build(args.out, args.seed)
    onset = ONSET_PASS * len(_tasks())
    print(f"Simulated database written to: {path}")
    print(f"  model '{MODEL_ID}', {PASSES * len(_tasks())} calls, injected model update at call {onset}")
    print("  SIMULATED DATA: never report anything from it as a result.")
    print()
    print("Open the dashboard on it with:")
    print(f"  driftguard dashboard --db-path {path}")


if __name__ == "__main__":
    main()
